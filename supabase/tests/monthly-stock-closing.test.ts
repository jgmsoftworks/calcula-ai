import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

const migration = readFileSync('supabase/migrations/20261119124000_fecha_estoque_no_banco.sql', 'utf8');
let db: PGlite;
let command: string;

async function runAt(instant: string) {
  await db.query(command.replace('statement_timestamp()', '$1::timestamptz'), [instant]);
}

async function balances(month: string) {
  return (await db.query(
    'select user_id, valor_estoque_fechamento, qtd_produtos_ativos from estoque_fechamentos_mensais where competencia = $1 order by user_id',
    [month],
  )).rows;
}

beforeAll(async () => {
  db = new PGlite();
  // PGlite has no pg_cron worker. Capture the command registered by the migration
  // and execute that same SQL against a fixed instant, with PostgreSQL time zones.
  await db.exec(`
    create schema cron;
    create table cron.job(jobid bigint generated by default as identity primary key,
      jobname text, database text default current_database(), username text default 'postgres',
      schedule text, command text, active boolean default true);
    create function cron.alter_job(bigint, schedule text, command text, active boolean) returns void
      language sql as $$ update cron.job set schedule=$2, command=$3, active=$4 where jobid=$1 $$;
    create function cron.schedule(text,text,text) returns bigint language sql as $$
      insert into cron.job(jobname,schedule,command) values ($1,$2,$3) returning jobid $$;
    insert into cron.job(jobid,jobname,command) values (41,'auto-fechamento-mensal','legacy');
    create table profiles(user_id int primary key, business_country text, region_confirmed boolean,
      created_at timestamptz default '2025-01-01Z');
    create table produtos(id int generated always as identity, user_id int, ativo boolean,
      estoque_atual numeric, custo_unitario numeric);
    create table estoque_fechamentos_mensais(user_id int, competencia text, valor_estoque_fechamento numeric,
      qtd_produtos_ativos int, primary key(user_id, competencia));
    insert into profiles(user_id,business_country,region_confirmed) values
      (1,'BR',true),(2,'PT',true),(3,'BR',true),(4,'BR',false);
    insert into profiles values (5,'BR',true,'2026-12-01T03:00:00Z');
    insert into produtos(user_id,ativo,estoque_atual,custo_unitario) values
      (2,true,3,4.50),(1,false,100,20),(4,true,4,1);
    insert into produtos(user_id,ativo,estoque_atual,custo_unitario)
      select 1,true,1,2 from generate_series(1,1001);
  `);
  await db.exec(migration);
  await db.exec(migration);
  const jobs = (await db.query<{ command: string; schedule: string; active: boolean }>(
    'select command, schedule, active from cron.job',
  )).rows;
  expect(jobs).toHaveLength(1);
  expect(jobs[0]).toMatchObject({ schedule: '0 * * * *', active: true });
  command = jobs[0].command;
});

afterAll(async () => { await db?.close(); });

describe('monthly stock closing in the database', () => {
  it('records the local December boundary once for each market, including zero and all active products', async () => {
    expect(await balances('2026-11')).toEqual([]);
    await runAt('2026-11-30T23:00:01Z');
    expect(await balances('2026-11')).toEqual([]);
    await runAt('2026-12-01T00:00:01Z');
    const portugal = { user_id: 2, valor_estoque_fechamento: '13.50', qtd_produtos_ativos: 1 };
    expect(await balances('2026-11')).toEqual([portugal]);
    await runAt('2026-12-01T03:00:01Z');
    const first = await balances('2026-11');
    expect(first).toEqual([
      { user_id: 1, valor_estoque_fechamento: '2002', qtd_produtos_ativos: 1001 },
      portugal,
      { user_id: 3, valor_estoque_fechamento: '0', qtd_produtos_ativos: 0 },
    ]);
    await db.exec('update produtos set custo_unitario = 7 where user_id = 1');
    await runAt('2026-12-01T03:00:08Z');
    expect(await balances('2026-11')).toEqual(first);
  });

  it('handles Lisbon summer time, year changes and missed months without backfilling', async () => {
    await runAt('2026-06-30T23:00:03Z');
    expect((await balances('2026-06')).map(row => row.user_id)).toEqual([2]);
    await runAt('2027-01-01T03:00:00Z');
    expect((await balances('2026-12')).map(row => row.user_id)).toEqual([1, 3, 5]);
    await runAt('2026-11-01T03:02:00Z');
    await runAt('2026-11-19T03:00:00Z');
    expect(await balances('2026-10')).toEqual([]);
  });
});
